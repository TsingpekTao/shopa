SELECT
  a.`user_id`,
  a.`phone`,
  a.`email`,
  a.`account_status`,
  GROUP_CONCAT(r.`role_code` ORDER BY r.`role_code`) AS role_codes
FROM `iam_user_auth` a
LEFT JOIN `iam_user_role` r
  ON r.`user_id` = a.`user_id`
 AND r.`status` = 1
WHERE a.`phone` = @admin_phone
GROUP BY a.`user_id`, a.`phone`, a.`email`, a.`account_status`;
